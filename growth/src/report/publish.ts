import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { HttpClient } from '../http.js';
import { ensureDir } from '../metrics/history.js';
import { safeLog, safeWarn } from '../redact.js';
import type { EnvConfig, GrowthConfig, GrowthReport } from '../types.js';

export function writeReportFiles(
  config: GrowthConfig,
  report: GrowthReport,
  reportsDir: string,
  dataDir: string,
): { reportPath: string; snapshotPath: string } {
  ensureDir(reportsDir);
  ensureDir(dataDir);
  const reportPath = join(reportsDir, `${report.date}.md`);
  const snapshotPath = join(dataDir, `${report.date}.json`);
  writeFileSync(reportPath, report.markdown, 'utf8');
  writeFileSync(snapshotPath, `${JSON.stringify(report.snapshot, null, 2)}\n`, 'utf8');
  return { reportPath, snapshotPath };
}

export async function publishGithubIssue(
  http: HttpClient,
  config: GrowthConfig,
  env: EnvConfig,
  report: GrowthReport,
): Promise<{ created: boolean; url?: string; skippedReason?: string }> {
  if (!env.publish) return { created: false, skippedReason: 'GROWTH_PUBLISH is not true' };
  if (!env.githubToken) return { created: false, skippedReason: 'GITHUB_TOKEN is missing' };

  const title = `Growth review ${report.date}`;
  const body = [
    report.markdown,
    '',
    '---',
    'Generated by `growth/` weekly agent. Drafts are for human review only.',
  ].join('\n');

  const headers = {
    Accept: 'application/vnd.github+json',
    Authorization: `Bearer ${env.githubToken}`,
    'User-Agent': 'usethishook-growth-agent',
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type': 'application/json',
  };

  const listUrl = `https://api.github.com/repos/${config.github.owner}/${config.github.repo}/issues?state=open&per_page=50`;
  const existing = await http.get(listUrl, { headers });
  if (!existing.ok) {
    safeWarn(`Unable to list issues (${existing.status}); creating a new issue`, [env.githubToken]);
  } else {
    const issues = existing.json<Array<{ number: number; title: string; html_url: string }>>();
    const match = issues.find((issue) => issue.title === title);
    if (match) {
      const update = await http.patch(
        `https://api.github.com/repos/${config.github.owner}/${config.github.repo}/issues/${match.number}`,
        {
          headers,
          body: JSON.stringify({ body }),
        },
      );
      if (!update.ok) {
        safeWarn(`Failed to update issue #${match.number}: ${update.status}`, [env.githubToken]);
        return { created: false, skippedReason: `update failed with ${update.status}` };
      }
      safeLog(`Updated growth issue #${match.number}`, [env.githubToken]);
      return { created: true, url: match.html_url };
    }
  }

  const create = await http.post(
    `https://api.github.com/repos/${config.github.owner}/${config.github.repo}/issues`,
    {
      headers,
      body: JSON.stringify({
        title,
        body,
        labels: ['growth'],
      }),
    },
  );
  if (!create.ok) {
    // Label may not exist; retry without labels.
    if (create.status === 422) {
      const retry = await http.post(
        `https://api.github.com/repos/${config.github.owner}/${config.github.repo}/issues`,
        {
          headers,
          body: JSON.stringify({ title, body }),
        },
      );
      if (retry.ok) {
        const issue = retry.json<{ html_url: string; number: number }>();
        safeLog(`Created growth issue #${issue.number}`, [env.githubToken]);
        return { created: true, url: issue.html_url };
      }
    }
    return { created: false, skippedReason: `create failed with ${create.status}` };
  }

  const issue = create.json<{ html_url: string; number: number }>();
  safeLog(`Created growth issue #${issue.number}`, [env.githubToken]);
  return { created: true, url: issue.html_url };
}
